CREATE TABLE shops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    shop_no VARCHAR(40) NOT NULL UNIQUE,
    standard_rent NUMERIC(14,2) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_shop_rent CHECK (standard_rent >= 0)
);

CREATE TABLE shop_tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    registration_no VARCHAR(40) NOT NULL UNIQUE,
    shop_id BIGINT NOT NULL,
    business_name VARCHAR(200) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    id_no VARCHAR(80) NOT NULL,
    mobile VARCHAR(40) NOT NULL,
    whatsapp VARCHAR(40),
    email VARCHAR(255) NOT NULL,
    address VARCHAR(600) NOT NULL,
    registered_date DATE NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    monthly_rent NUMERIC(14,2) NOT NULL,
    deposit_payable NUMERIC(14,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_tenant_shop FOREIGN KEY (shop_id) REFERENCES shops(id),
    CONSTRAINT ck_tenant_money CHECK (monthly_rent >= 0 AND deposit_payable >= 0)
);

CREATE TABLE shop_tenant_emergency_contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    shop_tenant_id BIGINT NOT NULL,
    contact_order INTEGER NOT NULL,
    contact_name VARCHAR(200) NOT NULL,
    phone VARCHAR(40) NOT NULL,
    relationship VARCHAR(100) NOT NULL,
    address VARCHAR(600),
    CONSTRAINT fk_tenant_contact FOREIGN KEY (shop_tenant_id) REFERENCES shop_tenants(id) ON DELETE CASCADE,
    CONSTRAINT uk_tenant_contact_order UNIQUE (shop_tenant_id, contact_order)
);

CREATE TABLE number_sequences (
    sequence_key VARCHAR(80) PRIMARY KEY,
    next_value BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor VARCHAR(100) NOT NULL,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_reference VARCHAR(120) NOT NULL,
    detail VARCHAR(1000)
);

CREATE INDEX ix_students_name ON students(last_name, first_name);
CREATE INDEX ix_students_status_room ON students(status, room_id);
CREATE INDEX ix_staff_name ON staff(last_name, first_name);
CREATE INDEX ix_staff_status ON staff(status);
CREATE INDEX ix_shop_tenants_status_shop ON shop_tenants(status, shop_id);
CREATE INDEX ix_audit_entity ON audit_events(entity_type, entity_reference, created_at);
