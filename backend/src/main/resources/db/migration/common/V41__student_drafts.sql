CREATE TABLE student_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    created_by VARCHAR(255) NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE,
    converted_at TIMESTAMP WITH TIME ZONE,
    converted_registration_no VARCHAR(40),
    first_name VARCHAR(100),
    middle_names VARCHAR(180),
    last_name VARCHAR(100),
    date_of_birth DATE,
    id_no VARCHAR(80),
    mobile VARCHAR(40),
    whatsapp VARCHAR(40),
    email VARCHAR(255),
    university VARCHAR(255),
    current_year VARCHAR(80),
    address VARCHAR(600),
    has_medical_condition BOOLEAN NOT NULL DEFAULT FALSE,
    medical_condition_details VARCHAR(2000),
    registered_date DATE,
    start_date DATE,
    emergency1_name VARCHAR(180),
    emergency1_contact VARCHAR(80),
    emergency1_relationship VARCHAR(100),
    emergency1_address VARCHAR(600),
    emergency2_name VARCHAR(180),
    emergency2_contact VARCHAR(80),
    emergency2_relationship VARCHAR(100),
    emergency2_address VARCHAR(600),
    notes VARCHAR(2000)
);

CREATE INDEX idx_student_drafts_created_by ON student_drafts(created_by);
CREATE INDEX idx_student_drafts_status ON student_drafts(status);
